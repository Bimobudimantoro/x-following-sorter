#!/usr/bin/env python3
"""
X Following Sorter — Auto-categorize X/Twitter following lists.

Input:  CSV from x-following-scraper (screen_name, name, verified_type, bio)
Output: HTML page with accounts grouped by category + CSV per category.
"""

import csv
import re
import sys
from pathlib import Path
from datetime import datetime

try:
    import tomllib  # Python 3.11+
except ImportError:
    import tomli as tomllib  # pip install tomli


# ─── Load categories ───────────────────────────────────────────────────

def load_categories(config_path="categories.toml"):
    """Parse categories.toml into a list of {label, color, patterns}."""
    data = tomllib.loads(Path(config_path).read_text())
    categories = []
    for c in data["categories"]:
        categories.append({
            "label": c["label"],
            "color": c["color"],
            "patterns": [re.compile(kw) for kw in c["keywords"]],
        })
    return categories


# ─── Classify ──────────────────────────────────────────────────────────

def classify_account(screen_name, name, bio, categories):
    """Return a list of category labels that match."""
    haystack = f"{screen_name} {name} {bio}"
    matched = []
    for cat in categories:
        if any(p.search(haystack) for p in cat["patterns"]):
            matched.append(cat["label"])
    return matched if matched else ["📦 Uncategorized"]


# ─── HTML output ───────────────────────────────────────────────────────

def build_html(groups, source_file):
    """Build a self-contained HTML report."""
    total = sum(len(v) for v in groups.values())

    rows_html = ""
    for cat_label, accounts in groups.items():
        if not accounts:
            continue
        color = "#7f8c8d"  # fallback for Uncategorized
        for c in groups:
            if c == cat_label:
                break
        # Find the color from a sample account (stored in group metadata)
        # We'll pass colors separately
        rows_html += f'<tr class="cat-header"><td colspan="5"><h2>{cat_label} <span class="count">{len(accounts)}</span></h2></td></tr>'
        for acc in accounts:
            verified_badge = ""
            if acc.get("verified_type"):
                verified_badge = f' <span class="verified">{acc["verified_type"]}</span>'
            clean_bio = (acc.get("bio") or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")[:180]
            rows_html += (
                f'<tr>'
                f'<td class="handle"><a href="https://x.com/{acc["screen_name"]}" target="_blank">@{acc["screen_name"]}</a></td>'
                f'<td class="name">{acc.get("name", "")}{verified_badge}</td>'
                f'<td class="bio">{clean_bio}</td>'
                f'</tr>'
            )

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>X Following Sorter — {source_file}</title>
<style>
* {{ margin:0; padding:0; box-sizing:border-box; }}
body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background:#0d1117; color:#c9d1d9; padding:20px; }}
h1 {{ color:#58a6ff; margin-bottom:4px; }}
.subtitle {{ color:#8b949e; margin-bottom:20px; font-size:14px; }}
table {{ width:100%; border-collapse:collapse; }}
.cat-header td {{ background:#161b22; padding:12px 16px; border-bottom:2px solid #30363d; }}
.cat-header h2 {{ color:#f0f6fc; font-size:18px; }}
.count {{ color:#8b949e; font-size:14px; font-weight:normal; margin-left:8px; }}
tr:not(.cat-header):hover {{ background:#1a2332; }}
td {{ padding:8px 16px; border-bottom:1px solid #21262d; font-size:14px; vertical-align:top; }}
.handle a {{ color:#58a6ff; text-decoration:none; font-weight:600; }}
.handle a:hover {{ text-decoration:underline; }}
.name {{ color:#f0f6fc; }}
.bio {{ color:#8b949e; max-width:500px; overflow:hidden; text-overflow:ellipsis; white-space:nowrap; }}
.verified {{ color:#d2a8ff; font-size:11px; background:#1c1f2b; padding:1px 6px; border-radius:4px; margin-left:4px; }}
.footer {{ color:#484f58; text-align:center; margin-top:30px; font-size:12px; }}
</style>
</head>
<body>
<h1>🔍 X Following Sorter</h1>
<p class="subtitle">Source: {source_file} &middot; {total:,} accounts &middot; {len([g for g in groups.values() if g])} categories &middot; Generated {datetime.now().strftime('%Y-%m-%d %H:%M')}</p>
<table>{rows_html}</table>
<p class="footer">Generated by x-following-sorter — <a href="https://github.com/Bimobudimantoro/x-following-sorter" style="color:#484f58">github.com/Bimobudimantoro/x-following-sorter</a></p>
</body>
</html>"""


# ─── CSV output ────────────────────────────────────────────────────────

def write_category_csvs(groups, out_dir):
    """Write one CSV per category into out_dir/."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for cat_label, accounts in groups.items():
        slug = re.sub(r"[^\w]", "_", cat_label).strip("_")
        path = out / f"{slug}.csv"
        with open(path, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=["screen_name", "name", "verified_type", "bio"])
            w.writeheader()
            w.writerows(accounts)


# ─── Main ──────────────────────────────────────────────────────────────

def main():
    if len(sys.argv) < 2:
        print("Usage: python sorter.py <input.csv> [categories.toml]")
        print("  input.csv must have columns: screen_name, name, verified_type, bio")
        sys.exit(1)

    csv_path = sys.argv[1]
    config_path = sys.argv[2] if len(sys.argv) > 2 else "categories.toml"

    categories = load_categories(config_path)
    print(f"Loaded {len(categories)} categories from {config_path}")

    # Read CSV
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        required = {"screen_name", "name", "verified_type", "bio"}
        missing = required - set(reader.fieldnames or [])
        if missing:
            print(f"ERROR: CSV missing columns: {missing}")
            sys.exit(1)
        accounts = [row for row in reader]

    print(f"Read {len(accounts):,} accounts from {csv_path}")

    # Classify
    groups = {}
    all_labels = [c["label"] for c in categories] + ["📦 Uncategorized"]
    for label in all_labels:
        groups[label] = []

    for acc in accounts:
        labels = classify_account(
            acc.get("screen_name", ""),
            acc.get("name", ""),
            acc.get("bio", ""),
            categories
        )
        # An account can belong to multiple categories
        for label in labels:
            groups[label].append({
                "screen_name": acc.get("screen_name", ""),
                "name": acc.get("name", ""),
                "verified_type": acc.get("verified_type", ""),
                "bio": acc.get("bio", ""),
            })

    # Print summary
    print("\n── Category breakdown ──")
    for label in all_labels:
        count = len(groups.get(label, []))
        bar = "█" * min(count // 5, 60) if count else ""
        print(f"  {label:40s} {count:>5}  {bar}")

    # Build HTML
    stem = Path(csv_path).stem
    html_path = f"{stem}_sorted.html"
    html = build_html(groups, Path(csv_path).name)
    Path(html_path).write_text(html, encoding="utf-8")
    print(f"\n✅ HTML report: {html_path}")

    # Write CSV per category
    out_dir = f"{stem}_sorted"
    write_category_csvs(groups, out_dir)
    print(f"✅ CSV per category: {out_dir}/")

    total_classified = sum(len(v) for k, v in groups.items() if k != "📦 Uncategorized")
    uncat = len(groups.get("📦 Uncategorized", []))
    print(f"\n🏁 {total_classified:,} classified, {uncat:,} uncategorized")


if __name__ == "__main__":
    main()